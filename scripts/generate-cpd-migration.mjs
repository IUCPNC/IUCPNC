import fs from 'node:fs/promises';
import {generateSQLiteDrizzleJson,generateSQLiteMigration} from 'drizzle-kit/api';
import * as core from '../db/schema.ts';
import * as profiles from '../db/profile-schema.ts';
import * as management from '../db/management-schema.ts';
import * as hub from '../db/people-hub-schema.ts';
import * as sync from '../db/sheets-sync-schema.ts';
import * as cpd from '../db/cpd-schema.ts';
const previous=JSON.parse(await fs.readFile('drizzle/meta/0006_snapshot.json','utf8'));
const current=await generateSQLiteDrizzleJson({...core,...profiles,...management,...hub,...sync,...cpd},previous.id);
const generated=await generateSQLiteMigration(previous,current),sql=generated.filter(s=>/`cpd_/.test(s));
if(sql.length!==16||sql.some(s=>!/^(CREATE TABLE `cpd_|CREATE INDEX `cpd_|CREATE UNIQUE INDEX `cpd_)/.test(s)))throw new Error('Unexpected CPD migration shape; inspect before applying.');
await fs.writeFile('drizzle/0009_cpd_training.sql',sql.join('\n--> statement-breakpoint\n')+'\n');
await fs.writeFile('drizzle/meta/0009_snapshot.json',JSON.stringify(current,null,2)+'\n');
const journal=JSON.parse(await fs.readFile('drizzle/meta/_journal.json','utf8'));
if(journal.entries.length!==9)throw new Error('Migration already generated or journal is unexpected.');
journal.entries.push({idx:9,version:'6',when:Date.now(),tag:'0009_cpd_training',breakpoints:true});
await fs.writeFile('drizzle/meta/_journal.json',JSON.stringify(journal,null,2)+'\n');
console.log(JSON.stringify({migration:'0009_cpd_training',statements:sql.length,schemaOnly:true}));
