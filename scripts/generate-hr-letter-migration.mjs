import fs from 'node:fs/promises';
import {generateSQLiteDrizzleJson,generateSQLiteMigration} from 'drizzle-kit/api';
import * as core from '../db/schema.ts';
import * as profiles from '../db/profile-schema.ts';
import * as management from '../db/management-schema.ts';
import * as hub from '../db/people-hub-schema.ts';
import * as sync from '../db/sheets-sync-schema.ts';
import * as cpd from '../db/cpd-schema.ts';
import * as attendance from '../db/attendance-schema.ts';
import * as service from '../db/hr-service-schema.ts';
const previous=JSON.parse(await fs.readFile('drizzle/meta/0012_snapshot.json','utf8'));
const current=await generateSQLiteDrizzleJson({...core,...profiles,...management,...hub,...sync,...cpd,...attendance,...service},previous.id);
const sql=await generateSQLiteMigration(previous,current);
if(sql.length!==2||sql.some(s=>!/^ALTER TABLE `hr_service_(requests|files)` ADD /.test(s)))throw Error('Unexpected letter schema delta');
const journal=JSON.parse(await fs.readFile('drizzle/meta/_journal.json','utf8'));if(journal.entries.length!==13)throw Error('Unexpected migration journal');
await fs.writeFile('drizzle/0013_hr_service_letters.sql',sql.join('\n--> statement-breakpoint\n')+'\n');
await fs.writeFile('drizzle/meta/0013_snapshot.json',JSON.stringify(current,null,2)+'\n');
journal.entries.push({idx:13,version:'6',when:Date.now(),tag:'0013_hr_service_letters',breakpoints:true});await fs.writeFile('drizzle/meta/_journal.json',JSON.stringify(journal,null,2)+'\n');
console.log(JSON.stringify({migration:'0013_hr_service_letters',statements:sql.length}));
