import assert from 'node:assert/strict';
import {fixture,employee,hr} from './test-profiles.mjs';
import {positionRoute} from '../worker/position-api.js';
import {businessDate} from '../worker/profile-schema.js';
const {sqlite,env}=fixture();let checks=0;
const call=async(path,b,user=hr,method='POST',expected=201)=>{const r=await positionRoute(new Request('https://nadi.test/api/positions'+path,{method,headers:{origin:'https://nadi.test','content-type':'application/json'},...(b?{body:JSON.stringify(b)}:{})}),env,{user,isPc:(_,email)=>email===hr.email});assert.equal(r.status,expected,await r.clone().text());checks++;return r.json();};
const entityBody={code:'TEST-COM',name:'Sample Quality Committee',kind:'Committee',status:'Draft',data:{effectiveDate:businessDate()}};
const entity=await call('/entities',entityBody);
const member={assignmentKind:'entity',entityId:entity.id,capacity:'Member',employeeId:'TEST-001',startDate:businessDate(),visibility:'Internal'};
await call('/assignments',member,hr,'POST',400);
assert.equal(sqlite.prepare("SELECT count(*) n FROM position_library WHERE id LIKE 'entity-%'").get().n,0);checks++;
await call('/entities/'+entity.id,{...entityBody,status:'Active',version:1},employee,'PUT',403);
await call('/entities/'+entity.id,{...entityBody,status:'Active',version:1},hr,'PUT',200);
await call('/entities/'+entity.id,{...entityBody,status:'Active',version:1},hr,'PUT',409);
await call('/assignments',member,employee,'POST',403);
await call('/assignments',{...member,primary:true},hr,'POST',400);
await call('/assignments',{...member,visibility:'Public'},hr,'POST',400);
await call('/assignments',{...member,capacity:'Director'},hr,'POST',400);
const before=sqlite.prepare('SELECT position,department,appraiser FROM employees WHERE employee_id=?').get('TEST-001');
const result=await call('/assignments',member);
assert.deepEqual(sqlite.prepare('SELECT position,department,appraiser FROM employees WHERE employee_id=?').get('TEST-001'),before);checks++;
const appointment=sqlite.prepare('SELECT * FROM position_assignments WHERE id=?').get(result.id);
assert.equal(appointment.is_primary,0);assert.equal(JSON.parse(appointment.data_json).entityId,entity.id);checks+=2;
await call('/assignments',member,hr,'POST',409);
await call('/assignments',{...member,employeeId:'TEST-002'});
assert.equal(sqlite.prepare("SELECT count(*) n FROM position_library WHERE id LIKE 'entity-%'").get().n,1);checks++;
const project=await call('/entities',{...entityBody,code:'TEST-PROJ',name:'Sample Project',kind:'Project',status:'Active'});
await call('/assignments',{...member,entityId:project.id,capacity:'Manager'});
const taskforce=await call('/entities',{...entityBody,code:'TEST-TASK',name:'Sample Taskforce',kind:'Taskforce',status:'Active'});
await call('/assignments',{...member,entityId:taskforce.id,capacity:'Lead'});
const view=await call('',null,employee,'GET',200);
assert(view.entities.some(e=>e.id===entity.id));assert(view.assignments.some(a=>a.id===result.id&&a.ackStatus==='Not Required'));checks+=2;
console.log(JSON.stringify({checks,status:'passed'}));sqlite.close();
