import fs from 'node:fs/promises';
import {generateSQLiteDrizzleJson,generateSQLiteMigration} from 'drizzle-kit/api';
import * as core from '../db/schema.ts';
import * as profiles from '../db/profile-schema.ts';
import * as management from '../db/management-schema.ts';
import * as hub from '../db/people-hub-schema.ts';
import * as sync from '../db/sheets-sync-schema.ts';
import * as cpd from '../db/cpd-schema.ts';
import * as attendance from '../db/attendance-schema.ts';
import * as service from '../db/hr-service-schema.ts';
import * as connect from '../db/connect-schema.ts';
import * as positions from '../db/position-schema.ts';
const previous=JSON.parse(await fs.readFile('drizzle/meta/0014_snapshot.json','utf8'));
const current=await generateSQLiteDrizzleJson({...core,...profiles,...management,...hub,...sync,...cpd,...attendance,...service,...connect,...positions},previous.id);
const sql=await generateSQLiteMigration(previous,current);
if(!sql.length||sql.some(s=>!/^CREATE (TABLE `position_|(?:UNIQUE )?INDEX `position_)/.test(s)))throw Error('Unexpected position schema delta');
const journal=JSON.parse(await fs.readFile('drizzle/meta/_journal.json','utf8'));if(journal.entries.length!==15)throw Error('Unexpected migration journal');
await fs.writeFile('drizzle/0015_position_management.sql',sql.join('\n--> statement-breakpoint\n')+'\n');
await fs.writeFile('drizzle/meta/0015_snapshot.json',JSON.stringify(current,null,2)+'\n');
journal.entries.push({idx:15,version:'6',when:Date.now(),tag:'0015_position_management',breakpoints:true});await fs.writeFile('drizzle/meta/_journal.json',JSON.stringify(journal,null,2)+'\n');
console.log(JSON.stringify({migration:'0015_position_management',statements:sql.length}));
